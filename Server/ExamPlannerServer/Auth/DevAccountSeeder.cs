using DatabaseConnection.DBContext;
using DatabaseConnection.model;
using Microsoft.AspNetCore.Identity;
using Microsoft.EntityFrameworkCore;

namespace ExamPlannerServer.Auth;

/// <summary>
/// DEVELOPMENT ONLY: a teacher and a student account to try the access tiers with (Program.cs calls this only
/// in Development; the values are in appsettings.Development.json). Runs at startup and never changes an
/// account that already has a password.
///
/// The student account belongs to the student with Seed:StudentNumber (for example STU-0002 is number 2), so
/// importing the Opslagsark gives it that student's enrollments. If that student was already imported (a user
/// without a password), the account is turned into the test login.
/// </summary>
public static class DevAccountSeeder
{
    public static async Task SeedAsync(IServiceProvider services, IConfiguration config, ILogger logger)
    {
        try
        {
            using var scope = services.CreateScope();
            var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();
            var hasher = scope.ServiceProvider.GetRequiredService<IPasswordHasher<User>>();

            await SeedTeacherAsync(db, hasher, config, logger);
            await SeedStudentAsync(db, hasher, config, logger);
        }
        catch (Exception ex)
        {
            // Usually means the database has not been migrated yet. The API still starts.
            logger.LogWarning(ex, "Could not create the development accounts. Has the database been migrated?");
        }
    }

    private static async Task SeedTeacherAsync(
        AppDbContext db, IPasswordHasher<User> hasher, IConfiguration config, ILogger logger)
    {
        var email = config["Seed:TeacherEmail"]?.Trim().ToLowerInvariant();
        var password = config["Seed:TeacherPassword"];
        if (string.IsNullOrEmpty(email) || string.IsNullOrEmpty(password) || await ExistsAsync(db, email))
            return;

        var teacher = new User { Email = email, Name = "Test Teacher", Role = Role.Teacher };
        teacher.HashedPassword = hasher.HashPassword(teacher, password);
        db.User.Add(teacher);
        await db.SaveChangesAsync();
        logger.LogInformation("Created the development teacher account {Email}", email);
    }

    private static async Task SeedStudentAsync(
        AppDbContext db, IPasswordHasher<User> hasher, IConfiguration config, ILogger logger)
    {
        var email = config["Seed:StudentEmail"]?.Trim().ToLowerInvariant();
        var password = config["Seed:StudentPassword"];
        if (string.IsNullOrEmpty(email) || string.IsNullOrEmpty(password)
            || !int.TryParse(config["Seed:StudentNumber"], out var number) || await ExistsAsync(db, email))
            return;

        var student = await db.Student.Include(s => s.User).FirstOrDefaultAsync(s => s.SourceStudentId == number);
        if (student is not null && student.User.HashedPassword.Length > 0)
        {
            logger.LogWarning("Student {Number} already has a login, so no development student account was made.", number);
            return;
        }

        var user = student?.User ?? new User { Role = Role.Student };
        user.Email = email;
        user.Name = "Test Student";
        user.HashedPassword = hasher.HashPassword(user, password);

        if (student is null)
        {
            // Student.Id is not generated by the database.
            var nextId = (await db.Student.MaxAsync(s => (int?)s.Id) ?? 0) + 1;
            db.Student.Add(new Student { Id = nextId, User = user, SourceStudentId = number });
        }

        await db.SaveChangesAsync();
        logger.LogInformation("Created the development student account {Email} (student {Number})", email, number);
    }

    private static Task<bool> ExistsAsync(AppDbContext db, string email) =>
        db.User.AnyAsync(u => u.Email.ToLower() == email);
}
